import { chromium } from '@playwright/test'
import { mkdirSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import assert from 'node:assert/strict'

const output = resolve(import.meta.dirname, '../artifacts/driver')
mkdirSync(output, { recursive: true })
const browser = await chromium.launch({ channel: 'chrome', headless: true })
const errors = []
const checks = []
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, locale: 'it-IT', timezoneId: 'Europe/Rome', acceptDownloads: true })
const page = await context.newPage()
page.on('pageerror', error => errors.push(error.message))
const base = 'http://127.0.0.1:5173'
try {
  for (const width of [1440, 1100, 1024, 390, 320]) {
    await page.setViewportSize({ width, height: 1000 })
    await page.goto(base + '/area-driver/turni')
    await page.getByText('Esporta PDF Turni Driver', { exact: false }).waitFor()
    const menu = page.getByRole('button', { name: 'Apri o chiudi il menu' })
    if (await menu.isVisible()) await menu.click()
    const links = page.locator('.navigation__areas a')
    assert.deepEqual(await links.allTextContents().then(texts => texts.map(t => t.trim())), ['Area Driver', 'Area Aziende', 'Area Enti'])
    assert.deepEqual(await links.evaluateAll(elements => elements.map(e => e.getAttribute('href'))), ['/area-driver', '/azienda/login', '/enti/login'])
    const sizes = await links.evaluateAll(elements => elements.map(e => { const s = getComputedStyle(e); return [e.getBoundingClientRect().height, s.padding, s.fontSize, s.fontWeight] }))
    assert.deepEqual(sizes[0], sizes[1]); assert.deepEqual(sizes[1], sizes[2])
    assert.equal(await links.first().getAttribute('aria-current'), 'page')
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true, `horizontal overflow at ${width}`)
    await page.screenshot({ path: resolve(output, `navbar-${width}.png`) })
    checks.push(`navbar ${width}px: CTA order, targets, equal geometry/type, active child route, no overflow`)
  }
  await page.setViewportSize({ width: 390, height: 1000 })
  await page.goto(base + '/area-driver/turni')
  await page.getByText('Esporta PDF Turni Driver', { exact: false }).waitFor()
  await page.locator('.page-container button.w-full').first().click()
  await page.getByRole('button', { name: 'Lavorato', exact: true }).click()
  await page.getByPlaceholder('Note (opzionale)...').fill('Test locale DTO')
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('attendance')))
  assert.equal(Object.values(saved)[0].status, 'Lavorato')
  assert.equal(Object.values(saved)[0].notes, 'Test locale DTO')
  assert.match(Object.keys(saved)[0], /^\d{4}-\d{2}-\d{2}$/)
  await page.reload()
  await page.getByText('Esporta PDF Turni Driver', { exact: false }).waitFor()
  assert.deepEqual(await page.evaluate(() => JSON.parse(localStorage.getItem('attendance'))), saved)
  const downloadPromise = page.waitForEvent('download')
  await page.getByText('Esporta PDF Turni Driver', { exact: false }).click()
  const download = await downloadPromise
  await download.saveAs(resolve(output, 'turni-browser.pdf'))
  await page.evaluate(() => { const a = JSON.parse(localStorage.getItem('attendance')); a['2000-01-01'] = { status: 'Ferie', notes: 'altro mese' }; localStorage.setItem('attendance', JSON.stringify(a)) })
  await page.reload()
  await page.getByRole('button', { name: 'Reset mese', exact: false }).click()
  await page.getByRole('button', { name: 'Azzera', exact: true }).click()
  assert.deepEqual(await page.evaluate(() => JSON.parse(localStorage.getItem('attendance'))), { '2000-01-01': { status: 'Ferie', notes: 'altro mese' } })
  checks.push('attendance: original page, save/reload, YYYY-MM-DD, notes, actual PDF download, reset only selected month')
  await page.goto(base + '/area-driver/contratto')
  await page.getByLabel('Tipo contratto').selectOption('part_time')
  await page.getByLabel('Ore settimanali').fill('24')
  await page.getByRole('button', { name: 'Sabato', exact: true }).click()
  await page.reload()
  await page.getByLabel('Tipo contratto').waitFor()
  assert.equal(await page.getByLabel('Ore settimanali').inputValue(), '24')
  assert.equal(await page.getByRole('button', { name: 'Sabato', exact: true }).getAttribute('aria-pressed'), 'true')
  checks.push('contract: original normalization, part-time, 24 weekly hours, Saturday persists')
  for (const width of [1440, 390]) {
    await page.setViewportSize({ width, height: 1000 })
    await page.goto(base + '/area-driver/busta-paga')
    await page.getByRole('tab', { name: 'Storico', exact: true }).waitFor()
    for (const label of ['Storico', 'Analisi', 'Confronto', 'Mese', 'Assistente']) {
      await page.getByRole('tab', { name: label, exact: true }).click()
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true, `payroll ${label} overflow at ${width}`)
    }
    await page.screenshot({ path: resolve(output, `payroll-${width}.png`) })
    checks.push(`payroll ${width}px: original tabs render without errors or overflow`)
  }
  await page.goto(base + '/area-driver/busta-paga')
  await page.locator('input[type=file]').setInputFiles(resolve(output, 'january2026SummaryAnonymizedFixture.pdf'))
  await page.getByRole('button', { name: 'Salva nello storico', exact: true }).waitFor()
  await page.getByRole('button', { name: 'Salva nello storico', exact: true }).click()
  await page.getByRole('tab', { name: 'Storico', exact: true }).waitFor()
  const payroll = await page.evaluate(() => JSON.parse(localStorage.getItem('driverPayroll.payslips') ?? '[]'))
  assert.equal(payroll.length, 1)
  assert.equal(payroll[0].summary.netAmount, 1909.64)
  assert.equal(payroll[0].fiscalDataVersion, 'fiscal-v1')
  await page.reload()
  await page.getByRole('tab', { name: 'Storico', exact: true }).click()
  assert.deepEqual(await page.evaluate(() => JSON.parse(localStorage.getItem('driverPayroll.payslips') ?? '[]')), payroll)
  await page.screenshot({ path: resolve(output, 'payroll-import-history.png'), fullPage: true })
  checks.push('real PDF picker -> original import/preview -> confirmation -> fiscal-v1 local history -> reload: net 1909.64')
  await page.setViewportSize({ width: 390, height: 667 })
  const preserved = await page.evaluate(() => [localStorage.getItem('attendance'), localStorage.getItem('driverContractProfile')])
  await page.getByRole('button', { name: 'Reset dati Payroll', exact: false }).click()
  const dialog = page.getByRole('alertdialog')
  await dialog.waitFor()
  const box = await dialog.boundingBox()
  assert(box.x >= 0 && box.x + box.width <= 390 && box.y >= 0 && box.y + box.height <= 667, 'dialog outside mobile viewport')
  await page.screenshot({ path: resolve(output, 'payroll-reset-mobile.png') })
  await dialog.getByRole('button', { name: 'Elimina tutto', exact: true }).click()
  await page.waitForFunction(() => localStorage.getItem('driverPayroll.payslips') === null)
  assert.deepEqual(await page.evaluate(() => [localStorage.getItem('attendance'), localStorage.getItem('driverContractProfile')]), preserved)
  checks.push('Payroll reset: mobile scoped Radix dialog, clears only Payroll and preserves attendance/contract')
  assert.deepEqual(errors, [])
  writeFileSync(resolve(output, 'browser-checks.json'), JSON.stringify({ passed: checks, errors }, null, 2))
  console.log(JSON.stringify({ passed: checks.length, checks, errors }))
} catch (error) {
  await page.screenshot({ path: resolve(output, 'browser-failure.png'), fullPage: true })
  console.error(JSON.stringify({ checks, errors, failure: error.message }))
  throw error
} finally { await browser.close() }
